private enum class BackupPage { EDITOR, PREVIEW, QUEUE }

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EmailBackupScreen(
    vm: EmailBackupViewModel,
    onBack: () -> Unit,
    onHistory: () -> Unit
) {
    val options by vm.options.collectAsStateWithLifecycle()
    val preview by vm.preview.collectAsStateWithLifecycle()
    val progress by vm.progress.collectAsStateWithLifecycle()
    val error by vm.error.collectAsStateWithLifecycle()
    val generated by vm.generated.collectAsStateWithLifecycle()
    val awaitingPart by vm.awaitingPart.collectAsStateWithLifecycle()
    val duplicate by vm.duplicate.collectAsStateWithLifecycle()
    var page by rememberSaveable { mutableStateOf(BackupPage.EDITOR) }
    var showDates by remember { mutableStateOf(false) }
    var showOriginalWarning by remember { mutableStateOf(false) }
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var launchError by remember { mutableStateOf<String?>(null) }
    val launcher = rememberLauncherForActivityResult(ActivityResultContracts.StartActivityForResult()) {
        // Returning from Gmail is not proof that the message was sent.
    }

    fun openPart(part: EmailBackupPartEntity) {
        scope.launch {
            try {
                val email = vm.createIntent(part.partId)
                launcher.launch(email.intent)
                vm.markOpened(part.partId)
            } catch (_: ActivityNotFoundException) {
                launchError = "no_email_app"
            } catch (error: Exception) {
                launchError = error.message ?: "open_email_failed"
            }
        }
    }

    LaunchedEffect(preview) {
        if (preview != null && page == BackupPage.EDITOR) page = BackupPage.PREVIEW
    }
    LaunchedEffect(generated?.backupId) {
        val backup = generated ?: return@LaunchedEffect
        page = BackupPage.QUEUE
        val first = backup.parts.firstOrNull() ?: return@LaunchedEffect
        try {
            val email = vm.createIntent(first.partId)
            launcher.launch(email.intent)
            vm.markOpened(first.partId)
        } catch (_: ActivityNotFoundException) {
            launchError = "no_email_app"
        } catch (error: Exception) {
            launchError = error.message ?: "open_email_failed"
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.email_backup_title)) },
                navigationIcon = {
                    TextButton(onClick = {
                        when (page) {
                            BackupPage.EDITOR -> onBack()
                            BackupPage.PREVIEW -> page = BackupPage.EDITOR
                            BackupPage.QUEUE -> onBack()
                        }
                    }) { Text(stringResource(R.string.back)) }
                },
                actions = {
                    TextButton(onClick = onHistory) {
                        Text(stringResource(R.string.backup_history))
                    }
                }
            )
        }
    ) { padding ->
        when (page) {
            BackupPage.EDITOR -> BackupEditor(
                modifier = Modifier.padding(padding),
                options = options,
                preview = preview,
                onRecipient = vm::updateRecipient,
                onRange = vm::updateRange,
                onCustomRange = { showDates = true },
                onCategory = vm::toggleCategory,
                onOtpRedaction = {
                    vm.updateRedaction { copy(redactOtp = it) }
                },
                onLongRedaction = {
                    vm.updateRedaction { copy(redactLongNumbers = it) }
                },
                onOriginal = {
                    if (it) showOriginalWarning = true
                    else vm.updateRedaction { copy(includeOriginalBodyInJson = false) }
                },
                onPreview = vm::preview
            )
            BackupPage.PREVIEW -> preview?.let {
                BackupPreview(
                    modifier = Modifier.padding(padding),
                    preview = it,
                    onEdit = { page = BackupPage.EDITOR },
                    onGenerate = vm::requestGenerate
                )
            }
            BackupPage.QUEUE -> BackupQueue(
                modifier = Modifier.padding(padding),
                generatedParts = generated?.parts.orEmpty(),
                awaitingPart = awaitingPart,
                onOpen = { partId ->
                    scope.launch {
                        val part = generated?.parts?.firstOrNull { it.partId == partId }
                        if (part != null) {
                            try {
                                val email = vm.createIntent(part.partId)
                                launcher.launch(email.intent)
                                vm.markOpened(part.partId)
                            } catch (_: ActivityNotFoundException) {
                                launchError = "no_email_app"
                            } catch (error: Exception) {
                                launchError = error.message ?: "open_email_failed"
                            }
                        }
                    }
                },
                onHistory = onHistory
            )
        }
        if (progress != null) {
            ProgressDialog(progress!!, vm::cancelWork)
        }
    }

    if (showDates) {
        BackupDateRangeDialog(
            onDismiss = { showDates = false },
            onSelect = { start, end ->
                vm.updateCustomRange(start, end)
                showDates = false
            }
        )
    }
    if (showOriginalWarning) {
        AlertDialog(
            onDismissRequest = { showOriginalWarning = false },
            title = { Text(stringResource(R.string.original_json_warning_title)) },
            text = { Text(stringResource(R.string.original_json_warning_body)) },
            confirmButton = {
                TextButton(onClick = {
                    vm.updateRedaction { copy(includeOriginalBodyInJson = true) }
                    showOriginalWarning = false
                }) { Text(stringResource(R.string.confirm)) }
            },
            dismissButton = {
                TextButton(onClick = { showOriginalWarning = false }) {
                    Text(stringResource(R.string.cancel))
                }
            }
        )
    }
    if (duplicate != null) {
        AlertDialog(
            onDismissRequest = vm::clearDuplicate,
            title = { Text(stringResource(R.string.duplicate_backup_title)) },
            text = {
                Text(stringResource(
                    if (duplicate!!.confirmed) R.string.duplicate_backup_confirmed
                    else R.string.duplicate_backup_unfinished
                ))
            },
            confirmButton = {
                TextButton(onClick = vm::generateAnyway) {
                    Text(stringResource(R.string.generate_again))
                }
            },
            dismissButton = {
                TextButton(onClick = {
                    if (duplicate!!.confirmed) vm.clearDuplicate() else vm.continueDuplicate()
                }) {
                    Text(stringResource(
                        if (duplicate!!.confirmed) R.string.cancel
                        else R.string.continue_existing_backup
                    ))
                }
            }
        )
    }
    val visibleError = error ?: launchError
    if (visibleError != null) {
        AlertDialog(
            onDismissRequest = {
                vm.clearError()
                launchError = null
            },
            title = { Text(stringResource(R.string.backup_error_title)) },
            text = { Text(backupErrorText(visibleError)) },
            confirmButton = {
                TextButton(onClick = {
                    vm.clearError()
                    launchError = null
                }) { Text(stringResource(R.string.confirm)) }
            }
        )
    }
    if (awaitingPart != null) {
        SendConfirmationDialog(
            part = awaitingPart!!,
            onSent = {
                vm.confirmPartSent(awaitingPart!!.partId) { next ->
                    if (next != null) openPart(next)
                }
            },
            onNotSent = { vm.reportPartNotSent(awaitingPart!!.partId) },
            onReopen = { openPart(awaitingPart!!) },
            onEnd = { vm.setAwaitingPart(null) }
        )
    }
}

@Composable
private fun BackupEditor(
    modifier: Modifier,
    options: com.example.jxsms.domain.backup.EmailBackupOptions,
    preview: com.example.jxsms.domain.backup.EmailBackupPreview?,
    onRecipient: (String) -> Unit,
    onRange: (EmailBackupRange) -> Unit,
    onCustomRange: () -> Unit,
    onCategory: (SmsCategory) -> Unit,
    onOtpRedaction: (Boolean) -> Unit,
    onLongRedaction: (Boolean) -> Unit,
    onOriginal: (Boolean) -> Unit,
    onPreview: () -> Unit
) {
    LazyColumn(modifier.fillMaxSize().padding(horizontal = 16.dp)) {
        item {
            Text(stringResource(R.string.recipient), fontWeight = FontWeight.Bold)
            OutlinedTextField(
                value = options.recipient,
                onValueChange = onRecipient,
                modifier = Modifier.fillMaxWidth(),
                singleLine = true,
                placeholder = { Text("user@example.com") }
            )
            SectionTitle(stringResource(R.string.backup_range))
            Row(
                Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                RangeChip(EmailBackupRange.UNBACKED, options.range, onRange)
                RangeChip(EmailBackupRange.LAST_7_DAYS, options.range, onRange)
                RangeChip(EmailBackupRange.LAST_30_DAYS, options.range, onRange)
            }
            Row(
                Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                RangeChip(EmailBackupRange.THIS_MONTH, options.range, onRange)
                FilterChip(
                    selected = options.range == EmailBackupRange.CUSTOM,
                    onClick = onCustomRange,
                    label = { Text(stringResource(R.string.range_custom)) }
                )
            }
            SectionTitle(stringResource(R.string.include_categories))
            SmsCategory.entries.forEach { category ->
                CheckLine(
                    stringResource(categoryStringRes(category)),
                    category in options.includedCategories,
                    { onCategory(category) }
                )
            }
            SectionTitle(stringResource(R.string.privacy_protection))
            SwitchLine(
                stringResource(R.string.redact_otp),
                options.redaction.redactOtp,
                onOtpRedaction
            )
            SwitchLine(
                stringResource(R.string.redact_long_numbers),
                options.redaction.redactLongNumbers,
                onLongRedaction
            )
            SwitchLine(
                stringResource(R.string.include_original_json),
                options.redaction.includeOriginalBodyInJson,
                onOriginal
            )
            preview?.let {
                Text(stringResource(R.string.estimated_messages, it.messages.size))
                Text(stringResource(R.string.estimated_emails, it.parts.size))
                Text(stringResource(
                    R.string.estimated_attachment,
                    it.estimatedAttachmentBytes / 1024
                ))
            }
            Spacer(Modifier.height(12.dp))
            Button(
                onClick = onPreview,
                enabled = options.recipient.isNotBlank() &&
                    options.includedCategories.isNotEmpty(),
                modifier = Modifier.fillMaxWidth()
            ) { Text(stringResource(R.string.preview)) }
            Spacer(Modifier.height(24.dp))
        }
    }
}

@Composable
private fun BackupPreview(
    modifier: Modifier,
    preview: com.example.jxsms.domain.backup.EmailBackupPreview,
    onEdit: () -> Unit,
    onGenerate: () -> Unit
) {
    LazyColumn(modifier.fillMaxSize().padding(horizontal = 16.dp)) {
        item {
            SectionTitle(stringResource(R.string.preview))
            InfoLine(stringResource(R.string.recipient), preview.options.recipient)
            InfoLine(
                stringResource(R.string.backup_range),
                formatRange(preview.resolvedRange.startInclusive, preview.resolvedRange.endInclusive)
            )
            InfoLine(stringResource(R.string.messages), preview.messages.size.toString())
            preview.categoryCounts.forEach { (category, count) ->
                InfoLine(stringResource(categoryStringRes(category)), count.toString())
            }
            InfoLine(stringResource(R.string.estimated_emails_label), preview.parts.size.toString())
            InfoLine(
                stringResource(R.string.estimated_attachment_label),
                "${preview.estimatedAttachmentBytes / 1024} KB"
            )
            InfoLine(
                stringResource(R.string.original_body_in_json),
                stringResource(
                    if (preview.options.redaction.includeOriginalBodyInJson) R.string.yes
                    else R.string.no
                )
            )
            SectionTitle(stringResource(R.string.first_subject))
            Text(preview.firstSubject)
            SectionTitle(stringResource(R.string.first_ten_messages))
        }
        items(preview.messages.take(10), key = { it.fingerprint }) { message ->
            Column(Modifier.padding(vertical = 8.dp)) {
                Text(
                    "${message.sms.contactName ?: message.sms.address} · " +
                        stringResource(categoryStringRes(message.sms.category)),
                    fontWeight = FontWeight.SemiBold
                )
                Text(message.redactedBody, maxLines = 5, overflow = TextOverflow.Ellipsis)
            }
        }
        item {
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                TextButton(onClick = onEdit, modifier = Modifier.weight(1f)) {
                    Text(stringResource(R.string.back_to_edit))
                }
                Button(onClick = onGenerate, modifier = Modifier.weight(1f)) {
                    Text(stringResource(R.string.generate_open_gmail))
                }
            }
            Spacer(Modifier.height(24.dp))
        }
    }
}

@Composable
private fun BackupQueue(
    modifier: Modifier,
    generatedParts: List<com.example.jxsms.domain.backup.GeneratedBackupPart>,
    awaitingPart: EmailBackupPartEntity?,
    onOpen: (String) -> Unit,
    onHistory: () -> Unit
) {
    Column(
        modifier.fillMaxSize().padding(20.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Text(
            stringResource(R.string.backup_generated, generatedParts.size),
            style = MaterialTheme.typography.titleLarge
        )
        Spacer(Modifier.height(12.dp))
        generatedParts.forEach { part ->
            TextButton(onClick = { onOpen(part.partId) }) {
                Text(stringResource(
                    R.string.open_email_part,
                    part.partNumber,
                    part.partCount
                ))
            }
        }
        if (awaitingPart != null) {
            Text(stringResource(R.string.waiting_for_confirmation, awaitingPart.partNumber))
        }
        Spacer(Modifier.height(12.dp))
        TextButton(onClick = onHistory) { Text(stringResource(R.string.backup_history)) }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun BackupDateRangeDialog(
    onDismiss: () -> Unit,
    onSelect: (LocalDate, LocalDate) -> Unit
) {
    val state = rememberDateRangePickerState()
    DatePickerDialog(
        onDismissRequest = onDismiss,
        confirmButton = {
            TextButton(
                onClick = {
                    val start = state.selectedStartDateMillis
                    val end = state.selectedEndDateMillis
                    if (start != null && end != null) {
                        onSelect(
                            Instant.ofEpochMilli(start).atZone(ZoneOffset.UTC).toLocalDate(),
                            Instant.ofEpochMilli(end).atZone(ZoneOffset.UTC).toLocalDate()
                        )
                    }
                },
                enabled = state.selectedStartDateMillis != null &&
                    state.selectedEndDateMillis != null
            ) { Text(stringResource(R.string.confirm)) }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) { Text(stringResource(R.string.cancel)) }
        }
    ) {
        DateRangePicker(
            state = state,
            modifier = Modifier.heightIn(max = 560.dp),
            title = { Text(stringResource(R.string.choose_date_range), Modifier.padding(16.dp)) }
        )
    }
}

@Composable
private fun ProgressDialog(progress: BackupProgress, onCancel: () -> Unit) {
    AlertDialog(
        onDismissRequest = {},
        title = {
            Text(stringResource(
                if (progress.stage == BackupProgress.Stage.PREPARING) {
                    R.string.preparing_messages
                } else {
                    R.string.generating_emails
                }
            ))
        },
        text = {
            Column {
                LinearProgressIndicator(
                    progress = {
                        if (progress.total <= 0) 0f
                        else progress.current.toFloat() / progress.total
                    },
                    modifier = Modifier.fillMaxWidth()
                )
                Text("${progress.current} / ${progress.total}")
            }
        },
        confirmButton = {
            TextButton(onClick = onCancel) { Text(stringResource(R.string.cancel)) }
        }
    )
}

