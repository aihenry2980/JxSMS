@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EmailBackupHistoryScreen(
    vm: EmailBackupViewModel,
    onBack: () -> Unit,
    onRegenerate: () -> Unit
) {
    val batches by vm.batches.collectAsStateWithLifecycle()
    val parts by vm.selectedHistoryParts.collectAsStateWithLifecycle()
    val awaitingPart by vm.awaitingPart.collectAsStateWithLifecycle()
    var selectedBatch by remember { mutableStateOf<EmailBackupBatchEntity?>(null) }
    var deleteBatch by remember { mutableStateOf<EmailBackupBatchEntity?>(null) }
    var confirmSent by remember { mutableStateOf<EmailBackupBatchEntity?>(null) }
    val scope = rememberCoroutineScope()
    val launcher = rememberLauncherForActivityResult(ActivityResultContracts.StartActivityForResult()) {}
    var error by remember { mutableStateOf<String?>(null) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.backup_history)) },
                navigationIcon = {
                    TextButton(onClick = onBack) { Text(stringResource(R.string.back)) }
                }
            )
        }
    ) { padding ->
        if (batches.isEmpty()) {
            Box(Modifier.padding(padding).fillMaxSize(), contentAlignment = Alignment.Center) {
                Text(stringResource(R.string.no_backup_history))
            }
        } else {
            LazyColumn(Modifier.padding(padding).padding(horizontal = 12.dp)) {
                items(batches, key = { it.backupId }) { batch ->
                    Column(Modifier.fillMaxWidth().padding(vertical = 10.dp)) {
                        Text(
                            DateFormat.getDateTimeInstance().format(Date(batch.createdAt)),
                            fontWeight = FontWeight.Bold
                        )
                        Text(batch.recipient)
                        Text(formatRange(batch.rangeStart, batch.rangeEnd))
                        Text(stringResource(
                            R.string.history_message_parts,
                            batch.totalMessageCount,
                            batch.partCount
                        ))
                        Text(backupStatusText(batch.status))
                        Row {
                            TextButton(onClick = {
                                selectedBatch = batch
                                vm.loadHistoryParts(batch.backupId)
                            }) { Text(stringResource(R.string.details)) }
                            TextButton(onClick = { confirmSent = batch }) {
                                Text(stringResource(R.string.mark_sent))
                            }
                            TextButton(onClick = {
                                vm.regenerate(batch, onRegenerate)
                            }) { Text(stringResource(R.string.regenerate)) }
                        }
                        Row {
                            TextButton(onClick = { vm.markBatchNotSent(batch.backupId) }) {
                                Text(stringResource(R.string.mark_not_sent))
                            }
                            TextButton(onClick = { deleteBatch = batch }) {
                                Text(stringResource(R.string.delete_record))
                            }
                        }
                    }
                }
            }
        }
    }
    selectedBatch?.let { batch ->
        AlertDialog(
            onDismissRequest = { selectedBatch = null },
            title = { Text(batch.backupId) },
            text = {
                LazyColumn(Modifier.heightIn(max = 420.dp)) {
                    items(parts, key = { it.partId }) { part ->
                        Row(
                            Modifier.fillMaxWidth().padding(vertical = 6.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                "${part.partNumber}/${batch.partCount} · ${part.status.name}",
                                Modifier.weight(1f)
                            )
                            if (part.status != EmailBackupPartStatus.CONFIRMED_SENT) {
                                TextButton(onClick = {
                                    scope.launch {
                                        try {
                                            val email = vm.createIntent(part.partId)
                                            launcher.launch(email.intent)
                                            vm.markOpened(part.partId)
                                        } catch (exception: Exception) {
                                            error = exception.message ?: "open_email_failed"
                                        }
                                    }
                                }) { Text(stringResource(R.string.continue_sending)) }
                            }
                        }
                    }
                }
            },
            confirmButton = {
                TextButton(onClick = { selectedBatch = null }) {
                    Text(stringResource(R.string.confirm))
                }
            }
        )
    }
    confirmSent?.let { batch ->
        AlertDialog(
            onDismissRequest = { confirmSent = null },
            title = { Text(stringResource(R.string.mark_sent)) },
            text = { Text(stringResource(R.string.manual_sent_warning)) },
            confirmButton = {
                TextButton(onClick = {
                    vm.markBatchSent(batch.backupId)
                    confirmSent = null
                }) { Text(stringResource(R.string.confirm)) }
            },
            dismissButton = {
                TextButton(onClick = { confirmSent = null }) {
                    Text(stringResource(R.string.cancel))
                }
            }
        )
    }
    deleteBatch?.let { batch ->
        AlertDialog(
            onDismissRequest = { deleteBatch = null },
            title = { Text(stringResource(R.string.delete_record)) },
            text = {
                Text(stringResource(
                    if (batch.status == EmailBackupBatchStatus.CONFIRMED_SENT) {
                        R.string.delete_confirmed_record_warning
                    } else {
                        R.string.delete_record_warning
                    }
                ))
            },
            confirmButton = {
                TextButton(onClick = {
                    vm.deleteRecord(batch.backupId)
                    deleteBatch = null
                }) { Text(stringResource(R.string.confirm)) }
            },
            dismissButton = {
                TextButton(onClick = { deleteBatch = null }) {
                    Text(stringResource(R.string.cancel))
                }
            }
        )
    }
    if (error != null) {
        AlertDialog(
            onDismissRequest = { error = null },
            title = { Text(stringResource(R.string.backup_error_title)) },
            text = { Text(backupErrorText(error!!)) },
            confirmButton = {
                TextButton(onClick = { error = null }) {
                    Text(stringResource(R.string.confirm))
                }
            }
        )
    }
    if (awaitingPart != null) {
        SendConfirmationDialog(
            part = awaitingPart!!,
            onSent = { vm.confirmPartSent(awaitingPart!!.partId) },
            onNotSent = { vm.reportPartNotSent(awaitingPart!!.partId) },
            onReopen = {
                scope.launch {
                    try {
                        val email = vm.createIntent(awaitingPart!!.partId)
                        launcher.launch(email.intent)
                        vm.markOpened(awaitingPart!!.partId)
                    } catch (exception: Exception) {
                        error = exception.message ?: "open_email_failed"
                    }
                }
            },
            onEnd = { vm.setAwaitingPart(null) }
        )
    }
}

@Composable
private fun RangeChip(
    value: EmailBackupRange,
    current: EmailBackupRange,
    onClick: (EmailBackupRange) -> Unit
) {
    FilterChip(
        selected = value == current,
        onClick = { onClick(value) },
        label = { Text(stringResource(rangeString(value))) }
    )
}

