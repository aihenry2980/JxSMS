    "invalid_recipient" -> R.string.error_invalid_recipient
    "sms_query_failed" -> R.string.error_sms_query
    "sms_permission_missing" -> R.string.error_sms_permission
    "no_matching_messages" -> R.string.error_no_matching_messages
