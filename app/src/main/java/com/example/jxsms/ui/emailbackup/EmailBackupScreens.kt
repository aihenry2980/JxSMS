    EmailBackupRange.LAST_7_DAYS -> R.string.range_7_days
    EmailBackupRange.LAST_30_DAYS -> R.string.range_30_days
    EmailBackupRange.THIS_MONTH -> R.string.range_this_month
    EmailBackupRange.CUSTOM -> R.string.range_custom
}

